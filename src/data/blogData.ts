export function getBlogPostByIdOrSlug(idOrSlug: string): BlogPost | undefined {
  if (!idOrSlug) return undefined;
  const decoded = decodeURIComponent(idOrSlug).trim().toLowerCase();
  return DEFAULT_BLOG_POSTS.find(
    (p) => p.id === idOrSlug || (p.slug && p.slug.toLowerCase() === decoded)
  );
}

export function getRelatedBlogPosts(currentPostId: string, limit = 3): BlogPost[] {
  return DEFAULT_BLOG_POSTS.filter((p) => p.id !== currentPostId).slice(0, limit);
}
